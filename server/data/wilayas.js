export const wilayaByCode = (c) => WILAYAS.find((w) => w.code === Number(c));

const stripAr = (s) => s.replace(/[ًٌٍَُِّْـ]/g, '').replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي');
export const normText = (s) => stripAr(String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, ''));

// يلقى الولاية في نص حر (أطول تطابق أولاً)
const INDEX = WILAYAS.flatMap((w) => [w.ar, w.fr, ...w.aliases].map((n) => ({ n: normText(n), w })))
  .sort((a, b) => b.n.length - a.n.length);
export function findWilaya(text) {
  if (!text) return null;
  const t = ' ' + normText(text).replace(/[^\p{L}\p{N}' ]+/gu, ' ') + ' ';
  const num = String(text).match(/\b(?:wilaya|ولاية|w)\s*(\d{1,2})\b/i);
  if (num && wilayaByCode(num[1])) return wilayaByCode(num[1]);
  for (const { n, w } of INDEX) {
    // يقبل حروف الجر الملصوقة: لبليدة، فوهران، بالجزائر، l blida
    const re = new RegExp(`(?:^|[\\s])(?:[لبفو]|ال|ل|لل|l |f |fi |a |à )?${n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?=[\\s])`, 'u');
    if (re.test(t)) return w;
  }
  return null;
}
